// Writes infra/cloudfront-functions/edge.js from edge.template.js: the
// CloudFront Function that does Markdown content negotiation and answers
// unknown /api/ and Markdown requests with proper 404 bodies. The function
// cannot list S3, so it carries a Bloom filter of every path that exists.

const fs = require("fs");
const path = require("path");
const { ROOT, SITE_URL } = require("./util");

const DIR = path.join(ROOT, "infra", "cloudfront-functions");
// CloudFront Functions reject code over 10 KB.
const MAX_BYTES = 10240;
const BITS_PER_KEY = 10;
const HASHES = 7;
const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

// Same arithmetic as fnv() in the template, kept in 32 bits.
function fnv(s, seed) {
  let h = seed >>> 0;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = (h + (h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24)) >>> 0;
  }
  return h;
}

function bloom(keys) {
  const m = Math.ceil((keys.length * BITS_PER_KEY) / 6) * 6;
  const bits = new Uint8Array(m);
  keys.forEach((k) => {
    const a = fnv(k, 2166136261);
    const b = (fnv(k, 3735928559) | 1) >>> 0;
    for (let i = 0; i < HASHES; i++) bits[(a + i * b) % m] = 1;
  });
  let out = "";
  for (let i = 0; i < m; i += 6) {
    let c = 0;
    for (let j = 0; j < 6; j++) c = (c << 1) | bits[i + j];
    out += B64[c];
  }
  return { m, data: out };
}

const MARKDOWN_404 = `# 404 Not Found

There is no page at \`{path}\` on LJ Web Management (www.ljwebmanagement.com). It may have moved or never existed.

Try one of these instead:

- [Site guide for AI agents (llms.txt)](${SITE_URL}/llms.txt): every section of the site, with links.
- [Sitemap](${SITE_URL}/sitemap.xml): every page.
- [Developer API and docs](${SITE_URL}/developers/): the JSON API and machine-readable files.
- [Home](${SITE_URL}/)

Every page is available as Markdown: send \`Accept: text/markdown\`.
`;

function build(keys) {
  const template = fs.readFileSync(path.join(DIR, "edge.template.js"), "utf8");
  const f = bloom(keys);
  const header = "// GENERATED by `npm run build` from edge.template.js. Do not edit.\n";
  const code =
    header +
    template
      .replace(/^(\/\/.*\n)+\n/, "")
      .replace("__BLOOM_BITS__", String(f.m))
      .replace("__BLOOM_HASHES__", String(HASHES))
      .replace("__BLOOM__", f.data)
      .replace("__MARKDOWN_404__", () => JSON.stringify(MARKDOWN_404));
  if (/__[A-Z0-9_]+__/.test(code)) throw new Error("edge.template.js has an unfilled placeholder");
  const bytes = Buffer.byteLength(code);
  if (bytes > MAX_BYTES) throw new Error("CloudFront Function is " + bytes + " bytes; the limit is " + MAX_BYTES);
  fs.writeFileSync(path.join(DIR, "edge.js"), code);
  console.log("  edge function: " + keys.length + " known paths, " + bytes + " bytes");
}

module.exports = { build, fnv, MAX_BYTES };
